#!/bin/bash
# Bidhata-Q5: collect the proprietary MediaTek files this build needs.
#
#   ./extract-files.sh <T-ROM_V.2.3 zip | j5052 system.img | mounted j5052 system dir> [sprout dir]
#
# Where the files come from:
#   - TIMMKOO's own T-ROM V2.3 (Android 5.0, board j5052), which Q5 owners download from
#     timmkoo.de. It matches the prebuilt 3.10 kernel. No root needed: files are read straight
#     out of system.img with debugfs.
#   - TheMuppets' public sprout (Android One, MT6582) vendor repo, for the few parts j5052 lacks.
#     Cloned automatically (sparse, ~40 MB) unless you pass a directory.
#
# Results: vendor/timmkoo/q5/proprietary + q5-vendor.mk, prebuilt/kernel, and three files in
# prebuilt/lib (thermal loader, FM config, speaker-gain-patched NVRAM defaults). None of them go
# into git.
set -e
SRC=${1:?usage: $0 <T-ROM zip | system.img | system dir> [sprout dir]}
SPR=$2
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
OUT=$ROOT/vendor/timmkoo/q5
WORK=$(mktemp -d); trap 'rm -rf "$WORK"' EXIT

# --- the j5052 system: a dir, an image, or the T-ROM zip ---------------------------------
if [ -d "$SRC" ]; then
    get() { cp -a "$SRC/$1" "$2"; }
else
    IMG=$SRC
    case "$SRC" in
        *.zip) echo "unpacking system.img from $(basename "$SRC")..."
               unzip -q -o "$SRC" system.img -d "$WORK"; IMG=$WORK/system.img ;;
    esac
    command -v debugfs >/dev/null || { echo "need debugfs (package e2fsprogs)" >&2; exit 1; }
    # empty files are real (some firmware slots are 0 bytes), so ask debugfs, not the size
    get() {
        debugfs -R "dump -p /$1 $2" "$IMG" 2>&1 | grep -q "File not found" && return 1
        [ -e "$2" ]
    }
fi

# --- sprout from TheMuppets ---------------------------------------------------------------
if [ -z "$SPR" ]; then
    echo "fetching sprout files from TheMuppets..."
    git clone -q --depth 1 --filter=blob:none --sparse -b cm-12.1 \
        https://github.com/TheMuppets/proprietary_vendor_google "$WORK/muppets"
    git -C "$WORK/muppets" sparse-checkout set sprout/proprietary
    SPR=$WORK/muppets/sprout/proprietary
fi

# --- copy the list ------------------------------------------------------------------------
rm -rf "$OUT/proprietary"; mkdir -p "$OUT/proprietary"
MK=$OUT/q5-vendor.mk
{ echo "# Generated by device/timmkoo/q5/extract-files.sh - do not edit"
  echo "PRODUCT_COPY_FILES += \\"; } > "$MK"
n=0
while read -r line; do
    case "$line" in ''|\#*) continue ;; esac
    case "$line" in sprout:*) f=${line#sprout:}; from=sprout ;; *) f=$line; from=j5052 ;; esac
    mkdir -p "$OUT/proprietary/$(dirname "$f")"
    if [ $from = sprout ]; then cp -a "$SPR/$f" "$OUT/proprietary/$f"
    else get "$f" "$OUT/proprietary/$f" || { echo "missing in j5052 system: $f" >&2; exit 1; }; fi
    echo "    vendor/timmkoo/q5/proprietary/$f:system/$f \\" >> "$MK"
    n=$((n+1))
done < "$HERE/proprietary-files.txt"
echo "" >> "$MK"

# --- the kernel: TIMMKOO's own 3.10 build, taken from the T-ROM boot.img ------------------------
mkdir -p "$HERE/prebuilt/lib"
if [ ! -d "$SRC" ]; then
    case "$SRC" in
        *.zip) unzip -q -o "$SRC" boot.img -d "$WORK"; BOOTIMG=$WORK/boot.img ;;
        *)     BOOTIMG=$(dirname "$SRC")/boot.img ;;
    esac
    python3 - "$BOOTIMG" "$HERE/prebuilt/kernel" <<'PY'
import struct, sys
b = open(sys.argv[1], 'rb').read()
if b[:8] != b'ANDROID!':
    sys.exit('not an Android boot image: ' + sys.argv[1])
size, = struct.unpack('<I', b[8:12]); page, = struct.unpack('<I', b[36:40])
open(sys.argv[2], 'wb').write(b[page:page + size])
PY
else
    [ -f "$HERE/prebuilt/kernel" ] || echo "note: pass the T-ROM zip to also get prebuilt/kernel" >&2
fi

# --- the three extra files in prebuilt/lib --------------------------------------------------
mkdir -p "$HERE/prebuilt/lib"
get lib/libmtcloader.so "$HERE/prebuilt/lib/libmtcloader.so"   # thermal_manager needs it
cp "$SPR/lib/libfmcust.so" "$HERE/prebuilt/lib/libfmcust.so"    # FM chip config (MT6627)
# Speaker: the default volume table holds the amp 11 dB under its limit. Raise the normal-mode
# speaker byte 128 -> 160 (3 dB under). File offset = audio_ver1_custom_default + 0x228.
python3 - "$OUT/proprietary/lib/libcustom_nvram.so" "$HERE/prebuilt/lib/libcustom_nvram.so" <<'PY'
import sys
b = bytearray(open(sys.argv[1], 'rb').read())
off = 0x9da8 + 0x228
if bytes(b[off:off+6]) != bytes([128, 120, 120, 120, 120, 120]):
    sys.exit('libcustom_nvram.so is not the expected j5052 build; speaker patch not applied')
b[off] = 160
open(sys.argv[2], 'wb').write(b)
PY

echo "done: $n files in $OUT, plus prebuilt/lib/{libmtcloader,libfmcust,libcustom_nvram}.so"
